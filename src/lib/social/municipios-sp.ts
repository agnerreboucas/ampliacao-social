/** Índice por nome normalizado, para casar com a segmentação dos anúncios. */
export const POR_NOME = new Map(
  MUNICIPIOS_SP.map((municipio) => [chaveDoNome(municipio.nome), municipio]),
);

/**
 * Nome sem acento, sem caixa e sem pontuação.
 *
 * A segmentação de um anúncio chega escrita à mão — "Sao Paulo", "SÃO PAULO
 * (+10 km)", "S. Bernardo do Campo". Casar com a lista oficial exige normalizar
 * dos dois lados, senão a cidade some do mapa sem ninguém notar.
 */
export function chaveDoNome(nome: string): string {
  return nome
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/\([^)]*\)/g, " ")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

/** Acha o município pelo nome escrito de qualquer jeito, ou `null`. */
export function acharMunicipio(nome: string): Municipio | null {
  return POR_NOME.get(chaveDoNome(nome)) ?? null;
}
