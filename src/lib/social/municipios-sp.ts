/**
 * Os 645 municípios de São Paulo.
 *
 * Vem da matriz do IPS — Índice de Proximidade com São Paulo — que a agência
 * montou: código do IBGE, nome, coordenadas, e para 600 deles a posição no
 * ranking, população de referência, IDHM 2010, distância da capital e a nota
 * do índice.
 *
 * **Por que os dados moram no código e não no banco.** Esta lista não é dado
 * de cliente: é a geografia do estado, igual para todo projeto, e não muda
 * entre uma campanha e outra. Mantê-la aqui faz o mapa funcionar também na
 * demonstração em HTML único, que roda sem servidor e sem banco.
 *
 * **O que o IPS é e o que não é.** É uma medida de *semelhança com a capital*,
 * composta por população (40%), proximidade geográfica (25%), IDHM 2010 (20%)
 * e escala urbana (15%). Não é índice de desempenho da campanha, nem de renda
 * atual: o IDHM é de 2010, e a própria matriz se declara preliminar. Serve
 * para priorizar onde olhar — não para concluir nada sozinho.
 *
 * Os 45 municípios sem posição no ranking ficam com zero nesses campos e a
 * plataforma os trata como "sem IPS", em vez de fingir uma nota.
 *
 * Formato compacto — tupla em vez de objeto — porque 645 objetos com nome de
 * campo repetido triplicariam o tamanho do arquivo sem ganhar nada.
 */

